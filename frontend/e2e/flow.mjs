// End-to-end flow in a real browser: upload -> map -> prepare -> dashboard filter -> forecast -> downloads.
import { chromium } from '@playwright/test'
const BASE = process.env.BASE || 'http://localhost:4173'
const CSV = process.argv[2]
const OUT = process.argv[3]
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome' })
const ctx = await browser.newContext({ viewport: { width: 1366, height: 900 }, acceptDownloads: true })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text().slice(0, 160)) })
const step = (s) => console.log('✓', s)

await page.goto(BASE + '/app/data', { waitUntil: 'networkidle' })
await page.getByText('In use').waitFor(); step('demo dataset opens automatically')
await page.setInputFiles('input[type=file]', CSV)
await page.getByText('Step 2 · Match your columns').waitFor({ timeout: 60000 }); step('upload read + columns detected')
const sel = (label) => page.getByRole('combobox', { name: label, exact: true })
console.log('  detected date =', await sel('Date').inputValue(), '| qty =', await sel('Quantity').inputValue(), '| price =', await sel('Unit price').inputValue(), '| region =', await sel('Region / country').inputValue())
await page.getByLabel('Cancelled-order prefix').fill('C')
await page.getByText('Preview quality report').click()
await page.locator('.kpi', { hasText: 'Duplicate rows' }).waitFor(); step('quality preview shown')
await page.getByText('Prepare data →').click()
await page.waitForURL('**/app/quality', { timeout: 120000 }); await page.getByText('Cleaning log').waitFor(); step('prepared, quality page shows cleaning log')
await page.screenshot({ path: `${OUT}/flow_quality.png` })

await page.goto(BASE + '/app/dashboard', { waitUntil: 'networkidle' })
await page.locator('.kpi', { hasText: 'Gross revenue' }).waitFor({ timeout: 60000 })
const before = await page.locator('.kpi', { hasText: 'Gross revenue' }).locator('.kpi-value').innerText()
await page.locator('.ms', { hasText: 'Regions' }).locator('input').click()
await page.locator('.ms-list li', { hasText: 'France' }).click()
await page.waitForTimeout(1500)
const after = await page.locator('.kpi', { hasText: 'Gross revenue' }).locator('.kpi-value').innerText()
console.log('  gross revenue all =', before, '| France only =', after)
if (before === after) throw new Error('filter did not change KPI'); step('region filter updates KPIs')
await page.getByLabel('From', { exact: true }).fill('2011-01-01'); await page.getByLabel('To', { exact: true }).fill('2011-06-30'); await page.waitForTimeout(1500)
const dated = await page.locator('.kpi', { hasText: 'Gross revenue' }).locator('.kpi-value').innerText()
console.log('  France H1 2011 =', dated); step('date filter updates KPIs')
await page.screenshot({ path: `${OUT}/flow_dashboard.png`, fullPage: true })
const [dl] = await Promise.all([page.waitForEvent('download'), page.getByText('Export trend CSV').click()])
console.log('  downloaded', dl.suggestedFilename()); step('dashboard CSV export')
await page.getByText('Clear filters').click(); await page.waitForTimeout(1200)

await page.goto(BASE + '/app/forecast', { waitUntil: 'networkidle' })
await page.locator('.kpi', { hasText: 'Next 3 months total' }).waitFor({ timeout: 120000 })
console.log('  forecast total =', await page.locator('.kpi', { hasText: 'Next 3 months total' }).innerText())
console.log('  model =', await page.locator('.kpi', { hasText: 'Selected model' }).locator('.kpi-value').innerText()); step('forecast generated')
await page.getByRole('radio', { name: 'Units' }).click(); await page.getByText('Run forecast').click()
await page.waitForTimeout(500); await page.locator('.kpi', { hasText: 'Next 3 months total' }).waitFor({ timeout: 120000 }); await page.waitForTimeout(3000)
console.log('  units forecast =', await page.locator('.kpi', { hasText: 'Next 3 months total' }).locator('.kpi-value').innerText()); step('target switch re-runs forecast')
await page.screenshot({ path: `${OUT}/flow_forecast.png`, fullPage: true })
const [d2] = await Promise.all([page.waitForEvent('download'), page.getByText('Forecast CSV').click()])
console.log('  downloaded', d2.suggestedFilename()); step('forecast CSV')

await page.goto(BASE + '/app/insights', { waitUntil: 'networkidle' }); await page.locator('.insight').first().waitFor({ timeout: 120000 })
console.log('  insights =', await page.locator('.insight').count()); step('insights')
await page.goto(BASE + '/app/reports', { waitUntil: 'networkidle' })
const [d3] = await Promise.all([page.waitForEvent('download', { timeout: 120000 }), page.locator('.card', { hasText: 'EDA report' }).getByRole('button').click()])
console.log('  downloaded', d3.suggestedFilename()); step('EDA HTML report')
await page.getByRole('button', { name: 'Reset analysis' }).click(); await page.waitForTimeout(3000)
console.log('  after reset dataset =', await page.locator('.dataset-chip b').innerText()); step('reset returns to demo data')
console.log('console/page errors:', errors.length ? errors : 'none')
await browser.close()
